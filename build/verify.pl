# Сверяет, что при перестройке шаблона не потерян и не искажён ни один символ.
my @RULES = (
  ['в течение 3 дней с даты согласования Этапа №1\.1' => '{{PAY_TECH2}}'],
  ['в течение 3 дней с даты завершения Этапа №2\.2'   => '{{PAY_TABLE}}'],
  ['всех планов и чертежей Этапов №1\.1, 1\.2'        => '{{TECH_STAGES_REF}}'],
  ['Этапов №2\.1, 2\.2' => 'Этапов №{{S_VIS1}}, {{S_VIS2}}'],
['Этап №1\.0' => 'Этап №{{S_TECH0}}'],
  ['Этапа №1\.1' => 'Этапа №{{S_TECH1}}'],  ['Этап №1\.1' => 'Этап №{{S_TECH1}}'],
  ['Этапа №1\.2' => 'Этапа №{{S_TECH2}}'],  ['Этап №1\.2' => 'Этап №{{S_TECH2}}'],
  ['Этапа №2\.0' => 'Этапа №{{S_VIS0}}'],   ['Этап №2\.0' => 'Этап №{{S_VIS0}}'],
  ['Этапа №2\.1' => 'Этапа №{{S_VIS1}}'],   ['Этап №2\.1' => 'Этап №{{S_VIS1}}'],
  ['Этапа №2\.2' => 'Этапа №{{S_VIS2}}'],   ['Этап №2\.2' => 'Этап №{{S_VIS2}}'],
  ['Этапа №3'    => 'Этапа №{{S_TABLE}}'],  ['Этап №3'    => 'Этап №{{S_TABLE}}'],
  ['Оплата 1\.1' => 'Оплата {{S_TECH1}}'],  ['Оплата 1\.2' => 'Оплата {{S_TECH2}}'],
  ['Оплата 2\.1' => 'Оплата {{S_VIS1}}'],   ['Оплата 2\.2' => 'Оплата {{S_VIS2}}'],
  ['Оплата 3 \|' => 'Оплата {{S_TABLE}} |'],
  ['\{\{TECH1_PR\}\}' => '{{TECH1_COST}}'],
  ['\{\{TECH2_PR\}\}' => '{{TECH2_COST}}'],
  ['\{\{TABLE_PR\}\}' => '{{TABLE_COST}}'],
  ['\(\{\{TOTAL_SUM_WORDS\}\}\)рублей\)' => '({{TOTAL_SUM_WORDS}})'],
  ['по горизонту пола \{\{AREA\}\}' => 'по горизонту пола {{AREA}} кв.м'],
  ['проекта:(?:\s|\xc2\xa0)*\{\{TOTAL_DAYS\}\}' => 'проекта: {{TOTAL_DAYS}} раб. дней'],
);
sub text_of {
  my ($p)=@_; open(my $f,'<:raw',$p) or die; my $x=<$f>; close $f;
  my $t='';
  while($x=~m{<w:p\b[^>]*>(.*?)</w:p>}gs){
    my $b=$1;
    while($b=~m{<w:t(?:\s[^>]*)?>(.*?)</w:t>}gs){ $t.=$1 }
    $t.="\n";
  }
  return $t;
}
sub canon {
  my ($t)=@_;
  $t =~ s/\{\{[#\/][A-Z0-9_]+\}\}//g;   # теги секций игнорируем: они переехали в свои абзацы
  $t =~ s/\xc2\xa0/ /g;                  # неразрывный пробел = обычный
  $t =~ s/\s+/ /g; $t =~ s/^ | $//g;
  return $t;
}
my $orig = text_of($ARGV[0]);
for my $r (@RULES) { my ($re,$rep)=@$r; $orig =~ s/$re/$rep/g; }
my $new = text_of($ARGV[1]);
my ($a,$b) = (canon($orig), canon($new));
if ($a eq $b) { print "OK: текст договора совпадает символ-в-символ (", length($a), " симв.)\n"; exit 0 }
print "РАСХОЖДЕНИЕ\n";
my $i=0; $i++ while $i<length($a) && $i<length($b) && substr($a,$i,1) eq substr($b,$i,1);
my $s = $i>60 ? $i-60 : 0;
print "первое различие на позиции $i\n";
print "ожидалось: ...", substr($a,$s,160), "...\n";
print "получено : ...", substr($b,$s,160), "...\n";
exit 1;
